
import json
import os
from pathlib import Path

import httpx
import streamlit as st

from catchmeup.collections import COLLECTIONS


# --------------------------------------------------
# Configuration
# --------------------------------------------------

API_BASE_URL = os.getenv(
    "CATCHMEUP_API_URL",
    "http://127.0.0.1:8000",
)


# --------------------------------------------------
# Page setup
# --------------------------------------------------

st.set_page_config(
    page_title="Catch Me Up",
    page_icon="📺",
    layout="wide",
)

st.title("📺 Catch Me Up")
st.caption(
    "Ask questions about what you've watched so far. "
    "Answers are generated by the existing Catch Me Up API."
)


# --------------------------------------------------
# Load episode metadata
# --------------------------------------------------

@st.cache_data
def load_episodes(data_path: str) -> list[dict]:
    """Load and validate ordered content units for a collection."""

    with Path(data_path).open("r", encoding="utf-8") as file:
        episodes = json.load(file)

    if not isinstance(episodes, list) or not episodes:
        raise ValueError(
            "The collection dataset must be a non-empty list."
        )

    for episode in episodes:
        if not isinstance(episode, dict):
            raise ValueError(
                "Every content unit must be a JSON object."
            )

        if "position" not in episode or "label" not in episode:
            raise ValueError(
                "Every content unit must contain position and label."
            )

        if not isinstance(episode["position"], int):
            raise ValueError(
                "Every content unit's position must be an integer."
            )

    positions = [episode["position"] for episode in episodes]

    if len(positions) != len(set(positions)):
        raise ValueError(
            "Content unit positions must be unique."
        )

    return sorted(episodes, key=lambda episode: episode["position"])


# --------------------------------------------------
# Sidebar: collection and viewing progress
# --------------------------------------------------

if not COLLECTIONS:
    st.error("No collections are registered in the backend.")
    st.stop()

with st.sidebar:
    st.header("Your viewing progress")

    collection_ids = list(COLLECTIONS.keys())

    collection_id = st.selectbox(
        "Collection",
        options=collection_ids,
        format_func=lambda cid: COLLECTIONS[cid].name,
    )

    config = COLLECTIONS[collection_id]

    try:
        episodes = load_episodes(str(config.data_path))
    except (
        OSError,
        json.JSONDecodeError,
        KeyError,
        ValueError,
    ) as exc:
        st.error(f"Could not load collection content: {exc}")
        st.stop()

    episode_by_label = {
        episode["label"]: episode for episode in episodes
    }

    if not episode_by_label:
        st.error("This collection contains no selectable units.")
        st.stop()

    selected_label = st.selectbox(
        f"I've reached this {config.unit_name}",
        options=list(episode_by_label.keys()),
    )

    selected_episode = episode_by_label[selected_label]
    current_position = selected_episode["position"]

    st.info(
        f"Answers should use only content available up to "
        f"{selected_label}. Select a position you've already reached."
    )


# --------------------------------------------------
# Question input
# --------------------------------------------------

st.subheader("What do you want to know?")

with st.form("question_form"):
    question = st.text_area(
        "Your question",
        placeholder=(
            "Why is Serena's return such a big deal?\n"
            "What do we know about Dan's family so far?"
        ),
        max_chars=2000,
        height=110,
    )

    submitted = st.form_submit_button(
        "Ask Catch Me Up",
        type="primary",
        use_container_width=True,
    )


# --------------------------------------------------
# Call the existing FastAPI endpoint
# --------------------------------------------------

if submitted:
    if not question.strip():
        st.warning("Please enter a question first.")
        st.stop()

    payload = {
        "collection_id": collection_id,
        "question": question.strip(),
        "current_position": current_position,
    }

    with st.spinner("Looking through the available content..."):
        try:
            response = httpx.post(
                f"{API_BASE_URL.rstrip('/')}/ask",
                json=payload,
                timeout=120.0,
            )

        except httpx.TimeoutException:
            st.error(
                "The request took too long. Please try again."
            )
            st.stop()

        except httpx.RequestError:
            st.error(
                "Couldn't connect to the Catch Me Up API. "
                "Make sure the API server is running."
            )
            st.stop()

    if response.status_code != 200:
        try:
            error_body = response.json()
            detail = error_body.get(
                "detail",
                "The API request failed.",
            )
        except (ValueError, AttributeError):
            detail = "The API returned an unexpected error."

        st.error(
            f"API error ({response.status_code}): {detail}"
        )
        st.stop()

    try:
        result = response.json()
    except ValueError:
        st.error("The API returned an invalid response.")
        st.stop()

    # --------------------------------------------------
    # Answer panel
    # --------------------------------------------------

    st.divider()
    st.subheader("Answer")

    status = result.get("status", "UNKNOWN")
    answer = result.get(
        "answer",
        "I couldn't find enough evidence in the available content.",
    )

    st.markdown(answer)

    # --------------------------------------------------
    # Validation and safety information
    # --------------------------------------------------

    with st.expander("Answer validation and safety details"):
        st.write("**Workflow status:**", status)

        citation_valid = result.get("citation_valid")

        if citation_valid is True:
            st.success("Citation ID validation passed.")
        elif citation_valid is False:
            st.warning("Citation validation reported an issue.")
        else:
            st.info(
                "Citation validation status was not provided."
            )

        citation_issues = result.get("citation_issues", [])

        if citation_issues:
            st.write("**Citation issues**")
            for issue in citation_issues:
                st.write(f"- {issue}")

        refusal_reason = result.get("refusal_reason")

        if refusal_reason:
            st.write("**Refusal reason:**", refusal_reason)

        st.write(
            "**Spoiler protection reported by API:**",
            result.get("spoiler_protected", False),
        )

        safety_flags = result.get("safety_flags", [])

        if safety_flags:
            st.write("**Safety flags**")
            for flag in safety_flags:
                st.write(f"- {flag}")

        st.write(
            "**Generation retries:**",
            result.get("retry_count", 0),
        )

    st.caption(
        "Citation validation checks citation IDs; it does not by itself "
        "prove that every sentence is semantically supported. "
        "Spoiler protection is not a guarantee of perfect detection."
    )
